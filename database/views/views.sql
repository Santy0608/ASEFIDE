JOIN FIDE_PUESTO_EMPRESA_ASOCIADO_TB PE 
    ON DA.ID_PUESTO_EMPRESA = PE.ID_PUESTO_EMPRESA

LEFT JOIN FIDE_ESTADO_TB E 
    ON U.ID_ESTADO = E.ID_ESTADO

LEFT JOIN FIDE_APORTE_TB A 
    ON DA.ID_DATOS_ASOCIADOS = A.ID_DATOS_ASOCIADOS

GROUP BY 
    U.ID_USUARIO,
    U.NOMBRE,
    U.APELLIDO_PATERNO,
    U.APELLIDO_MATERNO,
    U.NOMBRE_USUARIO,
    DA.ID_DATOS_ASOCIADOS,
