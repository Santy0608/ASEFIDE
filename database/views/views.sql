    COUNT(A.ID_APORTE) AS CANTIDAD_APORTES,
    NVL(SUM(A.MONTO), 0) AS TOTAL_APORTES,

    MAX(A.MONTO) KEEP (DENSE_RANK LAST ORDER BY A.FECHA_INICIO) AS APORTE_VIGENTE,

