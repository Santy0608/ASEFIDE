CREATE OR REPLACE VIEW V_FIDE_DASHBOARD_ACTIVIDADES_PROXIMAS AS
WITH ESTADO_ACTIVO AS (
    SELECT ID_ESTADO
    FROM FIDE_ESTADO_TB
    WHERE UPPER(NOMBRE) = 'ACTIVO'
    AND ROWNUM = 1
)
SELECT
    a.ID_ACTIVIDAD,
    a.NOMBRE                                 AS NOMBRE_ACTIVIDAD,
    a.FECHA_EVENTO,
    a.CUPO_TOTAL,
    l.NOMBRE_LUGAR                                 AS LUGAR,  -- nombre del lugar
    COUNT(ia.ID_INSCRIPCION)                 AS TOTAL_INSCRITOS,
    a.CUPO_TOTAL - COUNT(ia.ID_INSCRIPCION) AS CUPO_DISPONIBLE,
    ROUND(
        COUNT(ia.ID_INSCRIPCION) * 100.0
        / NULLIF(a.CUPO_TOTAL, 0),
        2
    )                                        AS PORCENTAJE_OCUPACION,
    (a.FECHA_EVENTO - TRUNC(SYSDATE))        AS DIAS_PARA_EVENTO
FROM FIDE_ACTIVIDAD_TB a
CROSS JOIN ESTADO_ACTIVO ea
LEFT JOIN FIDE_INSCRIPCIONES_ACTIVIDAD_TB ia
    ON a.ID_ACTIVIDAD = ia.ID_ACTIVIDAD
    AND ia.ID_ESTADO = ea.ID_ESTADO
LEFT JOIN FIDE_LUGAR_EVENTO_TB l
    ON a.ID_LUGAR_EVENTO = l.ID_LUGAR_EVENTO
WHERE a.FECHA_EVENTO >= TRUNC(SYSDATE)
  AND a.ID_ESTADO = ea.ID_ESTADO
GROUP BY
    a.ID_ACTIVIDAD,
    a.NOMBRE,
    a.FECHA_EVENTO,
    a.CUPO_TOTAL,
    l.NOMBRE_LUGAR
ORDER BY
    a.FECHA_EVENTO ASC
FETCH FIRST 5 ROWS ONLY
/


CREATE OR REPLACE VIEW V_FIDE_DASHBOARD_KPIS AS
SELECT
    (SELECT COUNT(*) FROM FIDE_USUARIO_TB u
     JOIN FIDE_ESTADO_TB e ON u.ID_ESTADO = e.ID_ESTADO
     WHERE UPPER(e.NOMBRE) = 'ACTIVO') AS ASOCIADOS_ACTIVOS,

    (SELECT NVL(SUM(SALDO_ACTUAL), 0)
     FROM FIDE_CUENTAS_AHORRO_TB) AS SALDO_TOTAL_AHORROS,

    (SELECT COUNT(*) FROM FIDE_PRESTAMO_TB p
     JOIN FIDE_ESTADO_TB e ON p.ID_ESTADO = e.ID_ESTADO
     WHERE UPPER(e.NOMBRE) != 'Completado') AS PRESTAMOS_PENDIENTES,

    (SELECT COUNT(*) FROM FIDE_TRANSACCION_TB
     WHERE TRUNC(FECHA_TRANSACCION, 'MM') = TRUNC(SYSDATE, 'MM')) AS TRANSACCIONES_MES
FROM DUAL
/


CREATE OR REPLACE VIEW V_DASHBOARD_PRESTAMOS_ESTADO AS
SELECT
    e.NOMBRE                          AS ESTADO,
    COUNT(p.ID_PRESTAMO)              AS TOTAL_PRESTAMOS,
    NVL(SUM(p.SALDO_PENDIENTE), 0)    AS SALDO_PENDIENTE_TOTAL,
    NVL(AVG(p.SALDO_PENDIENTE), 0)    AS SALDO_PROMEDIO,
    NVL(SUM(p.MONTO_SOLICITADO), 0)   AS MONTO_SOLICITADO_TOTAL,
    ROUND(
        COUNT(p.ID_PRESTAMO) * 100.0
        / NULLIF(SUM(COUNT(p.ID_PRESTAMO)) OVER (), 0),
        2
    )                                 AS PORCENTAJE_PRESTAMOS
FROM FIDE_ESTADO_TB e
LEFT JOIN FIDE_PRESTAMO_TB p
    ON e.ID_ESTADO = p.ID_ESTADO
WHERE e.ID_ESTADO IN (
    SELECT DISTINCT ID_ESTADO
    FROM FIDE_PRESTAMO_TB
)
GROUP BY
    e.ID_ESTADO,
    e.NOMBRE
ORDER BY
    SALDO_PENDIENTE_TOTAL DESC
/


