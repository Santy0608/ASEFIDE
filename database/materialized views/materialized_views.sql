CREATE MATERIALIZED VIEW FIDE_DASHBOARD_TRANSACCIONES_VM
    BUILD IMMEDIATE
    REFRESH COMPLETE ON DEMAND
    AS
SELECT
    TO_CHAR(t.FECHA_TRANSACCION, 'MON-YYYY') AS MES,
    TRUNC(t.FECHA_TRANSACCION, 'MM')          AS MES_ORDEN,
    tt.NOMBRE                                  AS TIPO,
    COUNT(*)                                   AS CANTIDAD,
    NVL(SUM(t.MONTO_TOTAL), 0)                AS MONTO_TOTAL
FROM FIDE_TRANSACCION_TB t
JOIN FIDE_TIPO_TRANSACCION_TB tt ON t.ID_TIPO_TRANSACCION = tt.ID_TIPO_TRANSACCION
WHERE t.FECHA_TRANSACCION >= ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -5)
GROUP BY
    TO_CHAR(t.FECHA_TRANSACCION, 'MON-YYYY'),
    TRUNC(t.FECHA_TRANSACCION, 'MM'),
    tt.NOMBRE
/


