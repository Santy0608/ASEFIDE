CREATE MATERIALIZED VIEW FIDE_DASHBOARD_TIPOS_AHORRO_VM
    BUILD IMMEDIATE
    REFRESH COMPLETE ON DEMAND
    AS
    WITH ESTADO_ACTIVO AS (
        SELECT ID_ESTADO 
        FROM FIDE_ESTADO_TB 
        WHERE UPPER(NOMBRE) = 'ACTIVO' 
        AND ROWNUM = 1
    )
    SELECT
        ta.ID_TIPO_AHORRO,
        ta.NOMBRE                                AS TIPO_AHORRO,
        COUNT(ca.ID_AHORRO)                      AS TOTAL_CUENTAS,
        NVL(SUM(ca.SALDO_ACTUAL), 0)             AS SALDO_TOTAL,
        NVL(AVG(ca.SALDO_ACTUAL), 0)             AS SALDO_PROMEDIO,
        ROUND(
            COUNT(ca.ID_AHORRO) * 100.0 
            / NULLIF(SUM(COUNT(ca.ID_AHORRO)) OVER (), 0), 
            2
        )                                        AS PORCENTAJE_CUENTAS
    FROM FIDE_TIPO_AHORRO_TB ta
    CROSS JOIN ESTADO_ACTIVO ea  
    LEFT JOIN FIDE_CUENTAS_AHORRO_TB ca 
        ON ta.ID_TIPO_AHORRO = ca.ID_TIPO_AHORRO 
        AND ca.ID_ESTADO = ea.ID_ESTADO 
    WHERE ta.ID_ESTADO = ea.ID_ESTADO
    GROUP BY 
        ta.ID_TIPO_AHORRO, 
        ta.NOMBRE;
/


